/**
 * Frontmatter parsing, inlined into every template.
 *
 * Twelve lines against a dependency the user has to know to install. The
 * markdown rankloop writes has a fixed, simple frontmatter block — this is
 * not a general YAML parser and does not pretend to be.
 */
const FRONTMATTER_TS = `type Frontmatter = Record<string, string>;

function parseFrontmatter(raw: string): { data: Frontmatter; body: string } {
  const match = /^---\\r?\\n([\\s\\S]*?)\\r?\\n---\\r?\\n?/.exec(raw);
  if (!match) return { data: {}, body: raw };
  const data: Frontmatter = {};
  for (const line of match[1].split(/\\r?\\n/)) {
    const idx = line.indexOf(":");
    if (idx === -1) continue;
    const key = line.slice(0, idx).trim();
    const value = line.slice(idx + 1).trim().replace(/^["']|["']$/g, "");
    if (key) data[key] = value;
  }
  return { data, body: raw.slice(match[0].length) };
}`;

