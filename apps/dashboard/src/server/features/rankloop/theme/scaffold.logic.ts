export interface ScaffoldPlan {
  files: ScaffoldFile[];
  /** The one dependency a stack may need, or null when it needs none. */
  requiredDependency: string | null;
}

/**
 * The files to add for a stack, in the extracted theme.
 *
 * Returns an empty plan for an unknown stack rather than a best guess —
 * `scaffoldPaths` already refuses to name paths for a framework it cannot
 * identify, and inventing them here would route around that refusal.
 */
export function buildScaffold(input: {
  stack: StackId;
  blogPath: string;
  theme: SiteTheme;
  /** package.json contents, to see whether a renderer is already installed. */
  packageJson: string | null;
}): ScaffoldPlan {
  const paths = scaffoldPaths(input.stack, input.blogPath);
  if (!paths) return { files: [], requiredDependency: null };

  // Same sanitiser scaffoldPaths uses. The root is interpolated into
  // generated source as well as into paths, so it has to be safe in both.
  const blogRoot = safeBlogRoot(input.blogPath);
  const existingRenderer = detectRenderer(input.packageJson);
  const css: ScaffoldFile = {
    path: paths.styles,
    content: renderThemeCss(input.theme) + CSS_BODY,
    purpose: "your site's colours, fonts and spacing as CSS variables",
  };

  switch (input.stack) {
    case "next-app":
    case "next-pages": {
      // Next has no built-in markdown renderer, so one dependency is
      // unavoidable. `marked` is the smallest well-known option; if the repo
      // already has a renderer we say so rather than asking for an install.
      const renderer = existingRenderer === "markdown-it" ? "markdown-it" : "marked";
      const needs = existingRenderer === null ? renderer : null;
      return {
        requiredDependency: needs,
        files: [
          {
            path: paths.index,
            content: nextAppIndex(blogRoot),
            purpose: "the blog index, listing every published post",
          },
          {
            path: paths.post,
            content: nextAppPost(blogRoot, renderer),
            purpose: "the post page, with Article schema and metadata",
          },
          css,
        ],
      };
    }
    case "astro":
      return {
        // Astro renders markdown itself. No install, and saying so is the
        // difference between a PR that merges and one that stalls on a
        // question.
        requiredDependency: null,
        files: [
          {
            path: paths.index,
            content: astroIndex(blogRoot),
            purpose: "the blog index, listing every published post",
          },
          {
            path: paths.post,
            content: astroPost(blogRoot),
            purpose: "the post page, with Article schema and metadata",
          },
          css,
        ],
      };
    case "static":
      return {
        requiredDependency: null,
        files: [
          {
            path: paths.index,
            content: staticIndex(blogRoot),
            purpose: "the blog index; rankloop appends posts between its markers",
          },
          {
            path: paths.post,
            content: staticPost(blogRoot),
            purpose: "the post template rankloop fills in per article",
          },
          css,
        ],
      };
    case "unknown":
      return { files: [], requiredDependency: null };
  }
}
