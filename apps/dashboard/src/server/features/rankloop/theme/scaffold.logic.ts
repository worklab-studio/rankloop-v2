function nextAppIndex(blogRoot: string): string {
  return `import fs from "node:fs";
import path from "node:path";
import Link from "next/link";
import "./rankloop-theme.css";

// Generated by rankloop. Posts are markdown in content/${blogRoot}/ —
// rankloop writes them there; this route lists them.

${FRONTMATTER_TS}

const POSTS_DIR = path.join(process.cwd(), "content", "${blogRoot}");

function allPosts() {
  if (!fs.existsSync(POSTS_DIR)) return [];
  return fs
    .readdirSync(POSTS_DIR)
    .filter((f) => f.endsWith(".md") && f !== "index.md")
    .map((file) => {
      const { data } = parseFrontmatter(
        fs.readFileSync(path.join(POSTS_DIR, file), "utf8"),
      );
      return {
        slug: file.replace(/\\.md$/, ""),
        title: data.title ?? file,
        description: data.description ?? "",
        date: data.date ?? "",
      };
    })
    .sort((a, b) => b.date.localeCompare(a.date));
}

export default function BlogIndex() {
  const posts = allPosts();
  return (
    <main className="rl-index">
      <h1>Blog</h1>
      {posts.length === 0 ? <p>No posts yet.</p> : null}
      {posts.map((post) => (
        <Link key={post.slug} href={\`/${blogRoot}/\${post.slug}\`} className="rl-card">
          <h2>{post.title}</h2>
          <p className="rl-meta">{post.date}</p>
          <p>{post.description}</p>
        </Link>
      ))}
    </main>
  );
}
`;
}

function nextAppPost(blogRoot: string, renderer: string): string {
  return `import fs from "node:fs";
import path from "node:path";
import { marked } from "${renderer}";
import "../rankloop-theme.css";

// Generated by rankloop. Renders one post from content/${blogRoot}/<slug>.md.

${FRONTMATTER_TS}

const POSTS_DIR = path.join(process.cwd(), "content", "${blogRoot}");

function readPost(slug: string) {
  const file = path.join(POSTS_DIR, \`\${slug}.md\`);
  if (!fs.existsSync(file)) return null;
  return parseFrontmatter(fs.readFileSync(file, "utf8"));
}

export function generateStaticParams() {
  if (!fs.existsSync(POSTS_DIR)) return [];
  return fs
    .readdirSync(POSTS_DIR)
    .filter((f) => f.endsWith(".md") && f !== "index.md")
    .map((f) => ({ slug: f.replace(/\\.md$/, "") }));
}

export async function generateMetadata({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const post = readPost(slug);
  if (!post) return {};
  return { title: post.data.title, description: post.data.description };
}

export default async function Post({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const post = readPost(slug);
  if (!post) return <main className="rl-post"><h1>Not found</h1></main>;

  const html = marked.parse(post.body) as string;
  // Article + FAQPage schema, mirroring what the laws already check for in
  // the markdown itself.
  const schema = {
    "@context": "https://schema.org",
    "@type": "Article",
    headline: post.data.title,
    description: post.data.description,
    datePublished: post.data.date,
  };

  return (
    <main className="rl-post">
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(schema) }}
      />
      <h1>{post.data.title}</h1>
      {post.data.description ? <p className="rl-dek">{post.data.description}</p> : null}
      <p className="rl-meta">{post.data.date}</p>
      <article dangerouslySetInnerHTML={{ __html: html }} />
    </main>
  );
}
`;
}

