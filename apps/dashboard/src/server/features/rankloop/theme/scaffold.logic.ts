// The files a scaffold PR writes (spec 0030).
//
// These read the markdown rankloop's GitHub adapter already publishes —
// `content/<blogPath>/<slug>.md` via repoPathFor — so the scaffold and the
// publisher agree on where posts live without either one configuring the
// other.
//
// Two rules shape every template here:
//
// 1. NO NEW DEPENDENCIES except a markdown renderer, and that one is
//    declared in the PR body with its install command. Frontmatter parsing
//    is inlined rather than pulling gray-matter: a scaffold whose build
//    fails because the user did not read a README is worse than no scaffold.
// 2. Structure matches what the publish laws already enforce — hero, table
//    of contents, H2 sections, FAQ, related posts. The laws check the
//    content; these templates give it somewhere to render.

import type { SiteTheme } from "@/server/features/rankloop/theme/theme.logic";
import { renderThemeCss } from "@/server/features/rankloop/theme/theme.logic";
import {
  safeBlogRoot,
  scaffoldPaths,
  type ScaffoldFile,
  type StackId,
} from "@/server/features/rankloop/theme/stack.logic";

/** Renderers we can use if the repo already has one. Checked so the PR can
 *  say "you already have this" instead of asking for an install nobody
 *  needs. */
const KNOWN_RENDERERS = ["marked", "markdown-it", "remark", "@next/mdx", "astro"] as const;

export function detectRenderer(packageJson: string | null): string | null {
  if (!packageJson) return null;
  return KNOWN_RENDERERS.find((dep) => new RegExp(`"${dep}"\\s*:`).test(packageJson)) ?? null;
}

