function astroIndex(blogRoot: string): string {
  return `---
// Generated by rankloop. Posts are markdown in content/${blogRoot}/.
import "../../styles/rankloop-theme.css";
const modules = import.meta.glob("../../../content/${blogRoot}/*.md", { eager: true });
const posts = Object.entries(modules)
  .map(([file, mod]: [string, any]) => ({
    slug: file.split("/").pop()!.replace(/\\.md$/, ""),
    ...(mod.frontmatter ?? {}),
  }))
  .sort((a, b) => String(b.date ?? "").localeCompare(String(a.date ?? "")));
---
<main class="rl-index">
  <h1>Blog</h1>
  {posts.length === 0 && <p>No posts yet.</p>}
  {posts.map((post) => (
    <a class="rl-card" href={\`/${blogRoot}/\${post.slug}\`}>
      <h2>{post.title ?? post.slug}</h2>
      <p class="rl-meta">{post.date}</p>
      <p>{post.description}</p>
    </a>
  ))}
</main>
`;
}

function astroPost(blogRoot: string): string {
  return `---
// Generated by rankloop. Astro renders the markdown itself — no extra
// dependency needed here.
import "../../styles/rankloop-theme.css";

export async function getStaticPaths() {
  const modules = import.meta.glob("../../../content/${blogRoot}/*.md", { eager: true });
  return Object.entries(modules).map(([file, mod]: [string, any]) => ({
    params: { slug: file.split("/").pop()!.replace(/\\.md$/, "") },
    props: { post: mod },
  }));
}

const { post } = Astro.props;
const { Content, frontmatter } = post;
---
<main class="rl-post">
  <script type="application/ld+json" set:html={JSON.stringify({
    "@context": "https://schema.org",
    "@type": "Article",
    headline: frontmatter.title,
    description: frontmatter.description,
    datePublished: frontmatter.date,
  })} />
  <h1>{frontmatter.title}</h1>
  {frontmatter.description && <p class="rl-dek">{frontmatter.description}</p>}
  <p class="rl-meta">{frontmatter.date}</p>
  <article><Content /></article>
</main>
`;
}

